const assert = require('assert');
const policy = require('../../../quickshell/.config/quickshell/mizu/services/NotificationPopupPolicy.js');
const a = { key: 'a', app: 'Chat', urgency: 1 };
const b = { key: 'b', app: 'Chat', urgency: 1 };
const critical = { key: 'c', app: 'Chat', urgency: 2 };
let result = policy.add([], a, 3);
result = policy.add(result.list, b, 3);
assert.deepStrictEqual(result.removed.map(x => x.key), ['a']);
assert.strictEqual(result.list[0].groupCount, 2);
assert.strictEqual(result.list[0].key, 'b');
result = policy.add(result.list, critical, 3);
assert.strictEqual(result.list.length, 2);
result = policy.add(result.list, {key: 'd', app: '', urgency: 1}, 3);
result = policy.add(result.list, {key: 'e', app: '', urgency: 1}, 3);
assert.strictEqual(result.list.length, 3);
assert.strictEqual(result.removed.length, 1);
assert.strictEqual(policy.readMs({title:'', body:'', urgency:1}), 5000);
assert.ok(policy.readMs({title:'', body:'', urgency:2}) > 5000);
assert.strictEqual(policy.readMs({title:'x'.repeat(1000), body:'', urgency:1}), 12000);
console.log('notification popup policy passed');
